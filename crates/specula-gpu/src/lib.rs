//! Specula GPU layer: hand-written Vulkan bindings and the render-hardware interface.
//!
//! - `vulkan-1` is loaded **at runtime** through `specula_sys::dynlib` (Windows: `LoadLibraryW` +
//!   `GetProcAddress`; later `dlopen` on Linux/macOS). All other entry points come through
//!   `vkGetInstanceProcAddr` / `vkGetDeviceProcAddr`. A machine without Vulkan gets a clean
//!   `GpuError`, never a failed process start.
//! - Validation layers (`VK_LAYER_KHRONOS_validation`) are enabled when requested and present;
//!   their messages are captured for agents via [`Gpu::take_validation_messages`].
//! - Everything works **headless** (offscreen targets + readback); a window swapchain is optional.
//!
//! # Rendering contract
//!
//! - Matrices are column-major `[f32; 16]` in Vulkan clip conventions (y down, depth 0..1) — build
//!   them with `specula_core::math` (`perspective_vk`, `look_at_rh`, `from_trs`).
//! - Triangle lists of [`Vertex`] (position, normal, sRGB vertex colour multiplied with a `Lit`
//!   draw's colour; white is neutral), D32 depth test (LESS with clear 1, or GREATER with clear 0
//!   when [`FrameDesc::reverse_z`] is set — use `perspective_vk_reverse_z`).
//! - Opaque draws ([`Material::Lit`]) come first, with no face culling; then the sky (if on);
//!   then blended draws (every other material), sorted far to near, with depth test on and depth
//!   writes off; then the overlay, last, over everything, after post-processing.
//! - With the default [`Environment`] and [`Surface`], a `Lit` draw is shaded exactly as in M0:
//!   `lit = color * (0.25 + 0.75 * max(dot(n, l), 0))`, light direction ≈ normalize(0.4, 0.8, 0.45).
//! - Per-frame data (camera, environment, lights, time, shadow cascades, fog, sky) and one record
//!   per draw (model, colours, surface, texture slots, bone palette) reach the shaders through
//!   buffer device addresses; push constants carry only the addresses, the material and the glass
//!   pass. One global descriptor set holds the shadow map and the bindless texture array.
//!
//! # Skinning
//!
//! A mesh uploaded with a skin stream ([`MeshStreams::skin`]: four bone indices and four unorm8
//! weights per vertex, a vertex buffer binding of its own) is skinned on the GPU when a draw
//! names its palette ([`DrawItem::skin`]): the first of its bone matrices in
//! [`FrameDesc::bones`], which every skinned draw of the frame shares (palettes one after
//! another, column-major `bind pose → pose` matrices: `specula_anim::write_gpu_matrices`). The
//! matrices are copied into the frame's upload buffer and read through its device address, so an
//! instanced batch of one creature mesh draws every instance with its own pose. Skinned variants
//! of the scene and shadow pipelines are built with the others; meshes without a skin stream (and
//! draws without a palette) use the plain pipelines, unchanged. Skinned draws are culled with
//! the posed bounds they give ([`DrawItem::bounds`]); without them they are never culled.
//!
//! # Textured materials
//!
//! A mesh with UVs ([`MeshStreams::uvs`], plus tangents, generated by [`generate_tangents`] when
//! not given) draws `Lit` with the textures its draw's [`Surface::textures`] names: base colour
//! (sRGB, alpha masking), a tangent-space normal map, metallic-roughness (glTF: roughness in G,
//! metalness in B) and emissive (sRGB) — all optional. Material textures come from
//! [`Gpu::upload_material_texture`]: a full mip chain ([`generate_mips`], in linear light for sRGB
//! data) and a sampler per [`TextureSampler`] (glTF filters and wrap modes, anisotropic filtering
//! when the device has it). Meshes without UVs and every other material are drawn as before.
//! Draws with textures don't multiply in the vertex colour (that hangs the Intel RaptorLake
//! driver, see `shaders/mesh_frag.glsl`): texture the colour instead. Draws of the same mesh
//! without textures use the plain pipeline and keep their vertex colours. Alpha-masked draws cut
//! their shadows too. Skinned and textured pipeline variants are built by the first upload of a
//! mesh with those streams (at loading time, never in a frame).
//!
//! # Frame passes
//!
//! `shadow` (sun shadow map, [`ShadowSettings`]) → `scene` (forward, all materials, the sky
//! [`SkySettings`], height fog [`FogSettings`]) → `post_bloom` → `post_tonemap` ([`BloomSettings`])
//! → `post_fxaa` ([`Environment::fxaa`]) → `overlay` ([`FrameDesc::overlay`]). Every feature is
//! **off by default**, and each one off is specialized out of the shaders (or its pass skipped),
//! so a frame without it renders exactly — bit for bit — what it rendered before the feature
//! existed. With bloom off and FXAA off the scene is tone mapped in the forward pass and written
//! straight to the target (no intermediate images: cheapest, and tile-GPU friendly).
//!
//! The passes run through a **render graph** (`graph.rs`): each declares the images it reads and
//! writes; the graph records every barrier and layout transition, picks load/store ops (an
//! attachment nothing reads later is never stored), and owns the intermediate images, depth
//! buffers and the shadow map. [`Gpu::last_graph`] shows a frame's graph as data, and
//! [`FrameStats::graph`] counts its barriers.
//!
//! # Performance
//!
//! - **Culling:** a draw whose mesh's bounding sphere lies outside the view frustum is skipped
//!   (standard or reversed Z, finite or infinite far plane).
//! - **Instancing:** opaque draws are sorted by mesh so equal ones merge into one instanced draw
//!   call; blended draws keep their far-to-near order and merge only when adjacent. Depth testing
//!   makes the opaque order irrelevant except where two opaque surfaces are exactly coplanar.
//! - **Pipelines** are all built up front: every variant for the offscreen format at
//!   [`Gpu::new`] and for the window's format at [`Gpu::attach_window`]. A `VkPipelineCache` can be
//!   persisted ([`Gpu::pipeline_cache_data`]) and fed back ([`GpuOptions::pipeline_cache`]).
//!   Call [`Gpu::mark_warm`] after loading; a pipeline created later is counted as a budget error
//!   ([`PipelineStats::created_after_warm`]).
//! - **Specialization:** the scene shaders are one source; each pipeline specializes it by
//!   feature (shadows, fog, HDR output) and the opaque pipeline to the `Lit` path alone, so a
//!   frame pays only for what it uses (on the Intel iGPU this cut the game scene's main pass from
//!   6.9 to 4.4 ms).
//! - **Budget** (`examples/bench.rs`, scene `game`: 2,000 instanced objects, shadows, bloom, fog,
//!   sky, FXAA, 200 overlay quads at 1600×900): about 7.5 ms GPU on the Intel RaptorLake iGPU
//!   with one fitted 2048² shadow map; each extra cascade adds about 1.2 ms.
//! - **Skinning** (bench `skinned_300`: 300 creatures × 20 bones, 576k triangles, shadows, fog):
//!   about 8.7 ms GPU on the Intel iGPU, of which skinning itself (vs the same frame in bind
//!   pose) is about 0.6 ms, mostly in the shadow pass; 0.23 ms on an RTX 4090 Laptop. Bone
//!   matrices cost 64 bytes each per frame in the upload buffer (300 × 20: 384 KB).
//! - **Statistics:** [`Gpu::last_frame_stats`] — GPU time per pass (timestamp queries, read without
//!   stalling), CPU time, draw calls, instances, triangles, culled draws, shadow casters, overlay
//!   quads, pipelines and memory.
//! - Colours given to the API are **sRGB** (as picked by humans/agents). Offscreen targets are
//!   `R8G8B8A8_SRGB`; the swapchain prefers `B8G8R8A8_SRGB`. Readback bytes are therefore sRGB RGBA8,
//!   ready to write as PNG.

