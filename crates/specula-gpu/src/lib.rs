/// Why an argument was rejected (machine-readable; `message` says the same in words).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ErrorReason {
    /// An id that names nothing (never created, or destroyed).
    UnknownId { kind: IdKind, id: u32 },
    /// A width or height of 0.
    ZeroSize { width: u32, height: u32 },
    /// A width or height above the device's limit.
    TooLarge { width: u32, height: u32, max: u32 },
    /// Pixel data of the wrong length.
    DataLength { given: u64, expected: u64 },
    /// A region that leaves the texture.
    RegionOutside { x: u32, y: u32, width: u32, height: u32, texture_width: u32, texture_height: u32 },
    /// A render graph declaration was rejected (a renderer bug: passes declared inconsistently).
    Graph(GraphError),
    /// A skinned draw's palette leaves [`FrameDesc::bones`]: draw `draw` starts it at `first`,
    /// its mesh's joints need `joints` matrices, and the frame has `bones`.
    PaletteOutside { draw: u32, first: u32, joints: u32, bones: u32 },
    /// A mesh's vertex stream has the wrong length (`vertex` = its length), or a skin vertex
    /// gives weight to joint 255 (`vertex` = that vertex).
    BadStream { stream: MeshStream, vertex: u32 },
}

