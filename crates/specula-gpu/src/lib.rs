/// How a material texture is sampled (glTF samplers map onto this). The default is trilinear,
/// repeating, with anisotropic filtering where the device has it.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub struct TextureSampler {
    pub mag: TextureFilter,
    pub min: TextureFilter,
    /// Filter between mip levels.
    pub mipmap: TextureFilter,
    pub wrap_u: TextureWrap,
    pub wrap_v: TextureWrap,
    /// Anisotropic filtering (up to 8×, when the device supports it; linear filters only).
    pub anisotropy: bool,
}

impl Default for TextureSampler {
    fn default() -> Self {
        TextureSampler {
            mag: TextureFilter::Linear,
            min: TextureFilter::Linear,
            mipmap: TextureFilter::Linear,
            wrap_u: TextureWrap::Repeat,
            wrap_v: TextureWrap::Repeat,
            anisotropy: true,
        }
    }
}

/// The textures of a `Lit` draw on a mesh with UVs (see the crate docs); all optional. Every id
/// must be a live texture (an unknown one is a structured error, like an unknown mesh).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct MaterialTextures {
    /// sRGB colour multiplied into the draw's colour (instead of the vertex colour, which
    /// textured materials ignore); alpha is coverage when `alpha_cutoff` > 0.
    pub base_color: Option<TextureId>,
    /// Tangent-space normal map (`Rgba8Unorm`, +Y up as glTF).
    pub normal: Option<TextureId>,
    /// Scales the normal map's X and Y (glTF `normalTexture.scale`).
    pub normal_scale: f32,
    /// Roughness (G) and metalness (B), multiplying the surface's (`Rgba8Unorm`).
    pub metallic_roughness: Option<TextureId>,
    /// Emissive colour (sRGB) multiplying `emissive_color` (white when that is `None`) times
    /// [`Surface::emissive`].
    pub emissive: Option<TextureId>,
    /// An emissive colour of the material's own (sRGB) times [`Surface::emissive`] (and the
    /// emissive texture). `None` without an emissive texture keeps the default: the surface
    /// colour times `emissive`.
    pub emissive_color: Option<[f32; 3]>,
    /// Alpha masking: fragments whose base colour alpha is below this are cut (0 = opaque), in
    /// the scene and in the sun's shadow.
    pub alpha_cutoff: f32,
}

impl MaterialTextures {
    pub const NONE: MaterialTextures = MaterialTextures {
        base_color: None,
        normal: None,
        normal_scale: 1.0,
        metallic_roughness: None,
        emissive: None,
        emissive_color: None,
        alpha_cutoff: 0.0,
    };

    /// Every texture id named.
    pub fn ids(&self) -> impl Iterator<Item = TextureId> {
        [self.base_color, self.normal, self.metallic_roughness, self.emissive].into_iter().flatten()
    }
}

impl Default for MaterialTextures {
    fn default() -> Self {
        MaterialTextures::NONE
    }
}

/// Pixel format of an uploaded texture (tightly packed rows, top row first).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum TextureFormat {
    /// One byte per pixel, e.g. a font atlas's coverage (sampled as red).
    R8,
    /// sRGB colour + linear alpha (pictures, UI art): sampled as linear colour.
    Rgba8Srgb,
    /// Raw data in 0..1 (masks, data textures).
    Rgba8Unorm,
}

impl TextureFormat {
    pub fn bytes_per_pixel(self) -> usize {
        match self {
            TextureFormat::R8 => 1,
            TextureFormat::Rgba8Srgb | TextureFormat::Rgba8Unorm => 4,
        }
    }
}

/// How an overlay quad uses its texture.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq, Hash)]
pub enum OverlayKind {
    /// colour × texel (straight alpha).
    #[default]
    Rgba,
    /// The texture's red channel is coverage (a font atlas): colour with alpha × coverage.
    AlphaMask,
}

/// A rectangle drawn over the finished frame (HUD, text, UI panels), after post-processing, in
/// list order. Pixel coordinates with the origin at the top left; blended with premultiplied
/// alpha. Shows in offscreen captures as on the window.
///
/// Beyond a flat fill: a vertical gradient (`color` → `color_bottom`), a border of `border` px
/// inside the edge with its own gradient, a soft edge (`feather`, for shadows), a clip rect, and
/// coloured triangles ([`OverlayQuad::triangle`]) that stay in list order with the quads.
/// Colours are sRGB with straight alpha; interpolation and blending happen in linear light.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct OverlayQuad {
    /// x, y, width, height in pixels.
    pub rect: [f32; 4],
    /// Texture coordinates of the rect's top-left and bottom-right corners: u0, v0, u1, v1.
    pub uv: [f32; 4],
    /// sRGB colour and straight (non-premultiplied) alpha; multiplies the texture.
    pub color: [f32; 4],
    /// `None` = a solid fill of `color`.
    pub texture: Option<TextureId>,
    pub kind: OverlayKind,
    /// Corner radius in pixels (0 = square). Edges are anti-aliased.
    pub radius: f32,
    /// Bottom colour of a vertical gradient from `color` at the top (`None` = flat).
    pub color_bottom: Option<[f32; 4]>,
    /// Border width in pixels, inside the edge (0 = none).
    pub border: f32,
    /// Border colour at the top and bottom (sRGB, straight alpha).
    pub border_color: [[f32; 4]; 2],
    /// Edge softness in pixels: 1 = crisp anti-aliasing; larger fades the edge over that width
    /// (soft shadows). At most [`MAX_OVERLAY_FEATHER`].
    pub feather: f32,
    /// Only pixels inside this x, y, width, height rect are drawn (`None` = everywhere).
    /// Edges snap to whole pixels.
    pub clip: Option<[f32; 4]>,
    /// Draw this triangle instead of the rect (`rect`, `uv`, `texture`, `radius`, `border` are
    /// ignored; `clip` applies).
    pub triangle: Option<OverlayTriangle>,
}

/// A triangle with per-vertex sRGB colours (straight alpha), interpolated in linear light.
/// Not anti-aliased by itself: give meshes an alpha fringe (as `specula-ui` does).
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct OverlayTriangle {
    pub points: [[f32; 2]; 3],
    pub colors: [[f32; 4]; 3],
}

/// Largest [`OverlayQuad::feather`], pixels.
pub const MAX_OVERLAY_FEATHER: f32 = 128.0;

impl Default for OverlayQuad {
    fn default() -> Self {
        OverlayQuad {
            rect: [0.0; 4],
            uv: [0.0, 0.0, 1.0, 1.0],
            color: [1.0; 4],
            texture: None,
            kind: OverlayKind::Rgba,
            radius: 0.0,
            color_bottom: None,
            border: 0.0,
            border_color: [[0.0; 4]; 2],
            feather: 1.0,
            clip: None,
            triangle: None,
        }
    }
}

impl OverlayQuad {
    /// A solid rectangle.
    pub fn solid(rect: [f32; 4], color: [f32; 4]) -> OverlayQuad {
        OverlayQuad { rect, color, ..Default::default() }
    }

    /// A textured rectangle showing `uv` of `texture`, tinted by `color`.
    pub fn textured(rect: [f32; 4], uv: [f32; 4], texture: TextureId, kind: OverlayKind, color: [f32; 4]) -> OverlayQuad {
        OverlayQuad { rect, uv, color, texture: Some(texture), kind, ..Default::default() }
    }

    /// A triangle with per-vertex colours.
    pub fn triangle(points: [[f32; 2]; 3], colors: [[f32; 4]; 3]) -> OverlayQuad {
        OverlayQuad { triangle: Some(OverlayTriangle { points, colors }), ..Default::default() }
    }
}

/// How a draw is shaded.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum Material {
    /// Opaque. Sun, ambient and point lights; optional emission, specular and metal.
    #[default]
    Lit,
    /// Blended thin glass or liquid shell: Fresnel reflection plus tinted, lit body of
    /// `color.a` opacity. Drawn twice, back faces then front faces.
    Glass,
    /// Blended soft dark disc on the XZ quad (a contact shadow); `color.a` is its darkness.
    BlobShadow,
    /// Ray-marched lava lamp inside the unit-cube proxy: glass vessel, liquid (`Surface::color2`)
    /// and moving wax (`color`), with a glow halo. Animated by [`FrameDesc::time_s`].
    LavaLamp,
}

impl Material {
    /// Drawn in the blended pass.
    pub fn blended(self) -> bool {
        self != Material::Lit
    }
}

/// Per-draw material parameters. The default gives M0's matte look.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Surface {
    /// Light emitted, as a multiple of `color` (0 = none). Values above 1 glow (HDR).
    pub emissive: f32,
    /// 0 = dielectric, 1 = metal (specular tinted by `color`, no diffuse).
    pub metallic: f32,
    /// 0 = mirror-sharp highlights, 1 = very broad.
    pub roughness: f32,
    /// Strength of highlights and reflections (0 = none, as in M0).
    pub specular: f32,
    /// Secondary sRGB colour (the lava lamp's liquid).
    pub color2: [f32; 3],
    /// Variation seed (the lava lamp's wax motion).
    pub seed: f32,
    /// Material textures (`Lit` on meshes with UVs; ignored otherwise).
    pub textures: MaterialTextures,
}

impl Default for Surface {
    fn default() -> Self {
        Surface { emissive: 0.0, metallic: 0.0, roughness: 0.5, specular: 0.0, color2: [0.0; 3], seed: 0.0, textures: MaterialTextures::NONE }
    }
}

#[derive(Clone, Copy, Debug, PartialEq)]
pub struct DrawItem {
    pub mesh: MeshId,
    /// Model (object → world) matrix, column-major.
    pub model: [f32; 16],
    /// sRGB colour; alpha is the opacity of blended materials (ignored by `Lit`).
    pub color: [f32; 4],
    pub material: Material,
    pub surface: Surface,
    /// Skinned meshes: index in [`FrameDesc::bones`] of this draw's first bone matrix (the
    /// mesh's joint indices count from it). `None` draws the bind pose. Ignored for meshes
    /// without a skin stream.
    pub skin: Option<u32>,
    /// A world-space bounding sphere (centre xyz, radius) for culling and shadow casting,
    /// replacing the mesh's. Skinned draws should give one that covers their pose: without it a
    /// skinned draw is never culled.
    pub bounds: Option<[f32; 4]>,
}

impl DrawItem {
    /// A matte (M0-style) draw.
    pub fn new(mesh: MeshId, model: [f32; 16], color: [f32; 4]) -> DrawItem {
        DrawItem { mesh, model, color, material: Material::Lit, surface: Surface::default(), skin: None, bounds: None }
    }
}

/// A point light: inverse-square falloff, smoothly cut to zero at `range`.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct PointLight {
    pub position: [f32; 3],
    /// sRGB.
    pub color: [f32; 3],
    /// Radiant intensity: at 1 m an intensity of 1 lights a white surface facing it fully.
    pub intensity: f32,
    /// Metres; no light beyond it.
    pub range: f32,
}

/// At most this many point lights per frame.
pub const MAX_POINT_LIGHTS: usize = 16;

/// At most this many overlay quads per frame.
pub const MAX_OVERLAY_QUADS: usize = 65_536;

/// At most this many bone matrices per frame ([`FrameDesc::bones`]): 64 MB of palettes.
pub const MAX_BONE_MATRICES: usize = 1 << 20;

/// Most shadow cascades.
pub const MAX_SHADOW_CASCADES: u32 = 4;

/// The sun's (or moon's) shadow: a cascaded shadow map fitted to the view. Off by default.
///
/// Only opaque (`Lit`) draws cast; every material receives (the lava lamp's glass included).
/// Cascades split the visible depth range (from the nearest visible draw to `distance`, or the
/// farthest visible draw if nearer); each is a square fitted around its slice, snapped to whole
/// texels so it does not shimmer as the camera moves.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ShadowSettings {
    pub enabled: bool,
    /// Texels per side of each cascade (clamped to 256..=8192).
    pub resolution: u32,
    /// 1..=[`MAX_SHADOW_CASCADES`]. One map fitted to what is visible suits compact, top-down
    /// views (and is cheapest: on the Intel iGPU each cascade costs about 1.2 ms in the game
    /// bench); more cascades keep near shadows sharp over long views.
    pub cascades: u32,
    /// View depth (m) where shadows end; they fade out over the last 10%.
    pub distance: f32,
    /// Penumbra radius in texels of the nearest cascade (0 = hard, hardware 2×2 filtering only).
    pub softness: f32,
    /// Scales the depth bias (constant and slope) and the receiver's offset along its normal.
    /// Raise it if surfaces shadow themselves ("acne"); lower it if shadows detach.
    pub bias: f32,
}

impl Default for ShadowSettings {
    fn default() -> Self {
        ShadowSettings { enabled: false, resolution: 2048, cascades: 1, distance: 80.0, softness: 1.5, bias: 1.0 }
    }
}

/// Bloom: light above `threshold` spreads into a soft glow. Off by default.
///
/// With bloom on the scene renders to a 16-bit float target; a chain of half-resolution levels
/// blurs what is bright, and the tonemap pass adds it back. Exposure applies first, so with the
/// default threshold of 1 only what would display brighter than white blooms (emissive surfaces,
/// bright highlights), not lit stone.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct BloomSettings {
    pub enabled: bool,
    /// Exposed brightness where bloom starts.
    pub threshold: f32,
    /// Softens the threshold over this range (0 = hard cut).
    pub knee: f32,
    /// Strength of the glow added back.
    pub intensity: f32,
    /// Blur levels (1..=8): each halves the resolution and widens the glow. Fewer = cheaper.
    pub levels: u32,
}

impl Default for BloomSettings {
    fn default() -> Self {
        BloomSettings { enabled: false, threshold: 1.0, knee: 0.5, intensity: 1.0, levels: 5 }
    }
}

/// An analytic sky drawn behind everything, instead of the flat clear colour. Off by default.
///
/// A vertical gradient (ground below the horizon, horizon colour at it, zenith overhead) and a
/// disc with a glow in the sun's direction (a moon, at night). Colours are sRGB; the sky is
/// scene light, so exposure, tone mapping, bloom and fog apply to it.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct SkySettings {
    pub enabled: bool,
    pub zenith: [f32; 3],
    pub horizon: [f32; 3],
    /// Below the horizon.
    pub ground: [f32; 3],
    /// Multiplies the gradient.
    pub intensity: f32,
    /// How quickly the horizon colour gives way to the zenith (higher = thinner horizon band).
    pub horizon_sharpness: f32,
    /// Angular radius of the sun/moon disc in degrees (0 = no disc).
    pub disc_size_deg: f32,
    /// Brightness of the disc, times the sun colour (above 1 blooms).
    pub disc_intensity: f32,
    /// Strength of the halo around the disc.
    pub glow: f32,
}

impl Default for SkySettings {
    /// A clear moonlit night (the Sepulcra palette).
    fn default() -> Self {
        SkySettings {
            enabled: false,
            zenith: [0.043, 0.063, 0.125],
            horizon: [0.165, 0.204, 0.282],
            ground: [0.08, 0.1, 0.14],
            intensity: 1.0,
            horizon_sharpness: 3.0,
            disc_size_deg: 1.2,
            disc_intensity: 6.0,
            glow: 0.25,
        }
    }
}

/// Exponential height fog. Off by default.
///
/// Density is `density` at `height` and changes by a factor e every `1 / falloff` metres: thick
/// below, thin above (`falloff` 0 = uniform fog). It starts `start_distance` metres from the
/// camera, applies to every material and to the sky (when the sky is on; otherwise the
/// background stays the clear colour), and brightens towards the sun by `sun_scatter`.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct FogSettings {
    pub enabled: bool,
    /// sRGB.
    pub color: [f32; 3],
    /// Extinction per metre at `height`.
    pub density: f32,
    /// Per metre of height.
    pub falloff: f32,
    /// Reference height (m).
    pub height: f32,
    pub start_distance: f32,
    /// In-scattered sunlight towards the sun (0 = none).
    pub sun_scatter: f32,
}

impl Default for FogSettings {
    fn default() -> Self {
        FogSettings {
            enabled: false,
            color: [0.165, 0.204, 0.282],
            density: 0.03,
            falloff: 0.25,
            height: 0.0,
            start_distance: 0.0,
            sun_scatter: 0.3,
        }
    }
}

/// Scene-wide lighting. The default reproduces M0.
